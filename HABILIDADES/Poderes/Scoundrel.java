package Poderes;
public class Scoundrel {

    public void adrenalina() {
        System.out.println("Ganha 2 AP imediatamente, mas perde 2 AP no próximo turno.");
    }

    public void contragolpe() {
        System.out.println("Salta sobre um inimigo e o apunhala pelas costas, garantindo um acerto crítico.");
    }

    public void cloroformio() {
        System.out.println("Destrói armadura mágica e tenta colocar o alvo para dormir.");
    }

    public void facaDeArremesso() {
        System.out.println("Lança uma faca que causa dano físico e pode apunhalar pelas costas.");
    }

    public void mantoEAdaga() {
        System.out.println("Teleporta você para um local alvo sem quebrar o modo furtivo ou invisibilidade.");
    }

    public void laminasCorrompidas() {
        System.out.println("Ataque de adaga que causa dano físico e aplica 'decaimento' e 'doença'.");
    }

    public void ordemDeMordaca() {
        System.out.println("Destrói armadura mágica e silencia o alvo.");
    }

    public void rupturaDeTeendoes() {
        System.out.println("Aplica um status que faz o alvo receber dano perfurante sempre que se mover.");
    }

    public void facaDeSerra() {
        System.out.println("Ataque que ignora armadura física e causa dano perfurante diretamente na vida, aplicando sangramento.");
    }

    public void bracosDormentes() {
        System.out.println("Ataque que causa dano físico e aplica 'atrofia', impedindo o uso de armas.");
    }

    public void crueldadeAterrorizante() {
        System.out.println("Ataque que causa dano físico, aplica sangramento e aterroriza o alvo.");
    }

    public void brinquedoDeCorda() {
        System.out.println("Invoca um bombardeiro mecânico que pode explodir, causando dano de fogo.");
    }

    public void adagasSacadas() {
        System.out.println("Uma sucessão de 5 ataques rápidos com adaga, cada um causando dano reduzido.");
    }

    public void lequeDeFacas() {
        System.out.println("Lança adagas em todos os inimigos ao redor, cada uma podendo causar acerto crítico.");
    }

    public void golpeMortal() {
        System.out.println("Causa dano massivo; o dano é dobrado se você estiver furtivo ou invisível. Mata instantaneamente se o alvo tiver menos de 20% de vida.");
    }
}
